#!/usr/bin/env node
/** Regenerate apps/web/public/manual.html from TeX写作智能体用户手册.md.
 *
 * Pipeline: pandoc (markdown_github reader; any 1.x/2.x works) → three
 * post-passes the old pandoc versions need:
 *   1. strip <table style="width:N%"> and <colgroup> — pandoc derives column
 *      widths from the *dash counts* of the pipe-table separator row, which
 *      squeezes a prose table to a sliver;
 *   2. headings carry exactly one id, in GitHub-slug form (the in-doc TOC
 *      links use those anchors);
 *   3. none of this touches the manual's own <br>/page-break divs — they are
 *      for the PDF export and inert in the browser.
 * Usage: node scripts/build-manual.mjs  (or: npm run build:manual) */
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const src = path.join(root, 'TeX写作智能体用户手册.md');
const out = path.join(root, 'apps/web/public/manual.html');

const body = execFileSync('pandoc', ['-f', 'markdown_github', '-t', 'html', src], { encoding: 'utf8' })
  // 1. de-squeeze tables: full width, natural column layout
  .replace(/<table style="width:\d+%;?">/g, '<table>')
  .replace(/<colgroup>[\s\S]*?<\/colgroup>\n?/g, '');

// 2. one GitHub-style id per heading (replaces pandoc's, which mangles CJK)
const slug = (text) => text
  .replace(/<[^>]+>/g, '')
  .trim().toLowerCase()
  .replace(/[^\p{L}\p{N}\-_ ]/gu, '')
  .replace(/\s+/g, '-') || 'section';
const fixedBody = body.replace(/<h([1-4])([^>]*)>([\s\S]*?)<\/h\1>/g, (m, lvl, attrs, text) => {
  const kept = attrs.replace(/\s*id="[^"]*"/g, '');
  return `<h${lvl} id="${slug(text)}"${kept}>${text}</h${lvl}>`;
});

